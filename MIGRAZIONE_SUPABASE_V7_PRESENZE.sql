drop policy if exists "DBW players insert" on public.dbw_players;
drop policy if exists "DBW players update" on public.dbw_players;
drop policy if exists "DBW players delete" on public.dbw_players;

create policy "DBW players select" on public.dbw_players for select to public using (true);
create policy "DBW players insert" on public.dbw_players for insert to public with check (true);
create policy "DBW players update" on public.dbw_players for update to public using (true) with check (true);
create policy "DBW players delete" on public.dbw_players for delete to public using (true);

drop policy if exists "DBW attendance select" on public.dbw_attendance;
drop policy if exists "DBW attendance insert" on public.dbw_attendance;
drop policy if exists "DBW attendance update" on public.dbw_attendance;
drop policy if exists "DBW attendance delete" on public.dbw_attendance;

create policy "DBW attendance select" on public.dbw_attendance for select to public using (true);
create policy "DBW attendance insert" on public.dbw_attendance for insert to public with check (true);
create policy "DBW attendance update" on public.dbw_attendance for update to public using (true) with check (true);
create policy "DBW attendance delete" on public.dbw_attendance for delete to public using (true);

grant select, insert, update, delete on public.dbw_players to anon, authenticated;
grant select, insert, update, delete on public.dbw_attendance to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

